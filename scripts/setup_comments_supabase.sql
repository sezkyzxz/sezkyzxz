-- 1. Buat tabel comments jika belum ada
CREATE TABLE IF NOT EXISTS public.comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    comment TEXT NOT NULL,
    avatar_url TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    is_approved BOOLEAN DEFAULT TRUE NOT NULL,
    is_pinned BOOLEAN DEFAULT FALSE NOT NULL,
    admin_reply TEXT,
    replied_at TIMESTAMPTZ
);

-- 2. Buat index agar sorting komentar cepat
CREATE INDEX IF NOT EXISTS comments_created_at_idx ON public.comments (created_at DESC);
CREATE INDEX IF NOT EXISTS comments_pinned_idx ON public.comments (is_pinned DESC, created_at DESC);

-- 3. Aktifkan Row Level Security (RLS)
ALTER TABLE public.comments ENABLE ROW LEVEL SECURITY;

-- 4. Hapus policy lama jika ada agar bersih
DROP POLICY IF EXISTS "Allow public read on comments" ON public.comments;
DROP POLICY IF EXISTS "Allow public insert on comments" ON public.comments;
DROP POLICY IF EXISTS "Allow service role full access on comments" ON public.comments;
DROP POLICY IF EXISTS "Allow authenticated full access on comments" ON public.comments;

-- 5. Kebijakan RLS: Pengunjung / publik bisa membaca komentar yang statusnya approved
CREATE POLICY "Allow public read on comments"
ON public.comments FOR SELECT
USING (is_approved = true);

-- 6. Kebijakan RLS: Siapapun (publik) boleh mengirim komentar baru
CREATE POLICY "Allow public insert on comments"
ON public.comments FOR INSERT
WITH CHECK (true);

-- 7. Kebijakan RLS: Admin / User yang login (authenticated) memiliki akses penuh (lihat, ubah, hapus, pin, balas)
CREATE POLICY "Allow authenticated full access on comments"
ON public.comments FOR ALL
TO authenticated
USING (true)
WITH CHECK (true);

